import { startQaServer } from './scripts/qa-server.mjs';
const server = await startQaServer({ port: 0 });
const u = await fetch(`${server.url}/api/board?grams=500&dest=tel-aviv&variant=unspecified`).then(r=>r.json());
console.log('UNSTATED BEST:', JSON.stringify(u.best, null, 1).slice(0, 4000));
const c = await fetch(`${server.url}/api/board?grams=500&dest=tel-aviv&variant=classico`).then(r=>r.json());
const x8 = c.ranked.find(q => q.key.endsWith('x8'));
console.log('X8 product:', JSON.stringify(x8.product));
console.log('X8 units/ordered:', x8.units, x8.orderedGrams, 'total', x8.totalIls);
console.log('PICKUP[0]:', JSON.stringify(c.pickup[0], null, 1).slice(0, 1800));
console.log('PICKUP[1] labels:', JSON.stringify(c.pickup[1]?.labels), 'shipmode', c.pickup[1]?.shipping?.mode);
console.log('CM single:', JSON.stringify(c.ranked[1], null, 1).slice(0, 1500));
await server.close();
